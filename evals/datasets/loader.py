"""Golden-dataset schema + loader.

Each `GoldenAd` is a labeled ad: the ad copy, its ground-truth claims, the
authoritative source facts, and the expected verdict + blocker rule keys (the
labels). The dataset is generated by scripts/build_golden.py and consumed by
the eval suites in evals/deepeval/.
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import BaseModel, Field

GOLDEN_PATH = Path(__file__).resolve().parent / "golden.json"


class GoldenAd(BaseModel):
    id: str
    scenario: str
    jurisdiction: str
    source_facts: dict  # {"vehicle": {...}, "offer": {...}} (JSON-mode values)
    ad_copy: str
    true_claims: dict  # ground-truth AdClaims (JSON-mode)
    expected_verdict: str  # PASS / FAIL / REQUIRES_REVIEW
    expected_blocker_rule_keys: list[str] = Field(default_factory=list)
    notes: str = ""


def load_golden(path: Path | str = GOLDEN_PATH) -> list[GoldenAd]:
    data = json.loads(Path(path).read_text())
    return [GoldenAd.model_validate(entry) for entry in data]
